import type { Metadata } from 'next'

export const metadata: Metadata = { title: '功能说明 · 映知文档' }

export default function DocsFeaturesPage() {
  return (
    <article className="docs-article">
      <h1>功能说明</h1>
      <p className="docs-lede">按使用顺序介绍映知的主要能力。所有描述以当前版本实际功能为准。</p>

      <h2 id="workspace">工作台与视频库</h2>
      <p>
        工作台（首页）汇总处理中的任务、最近的视频和最近的问答会话，存在排队或运行任务时会自动刷新；失败任务可以直接重试。视频库展示全部视频，支持按状态筛选和关键词搜索。每张视频卡片下方的四段进度条依次表示「入库 / 转写 / 画面分析 / 检索索引」，悬停可查看各段状态。
      </p>

      <h2 id="upload">上传与链接导入</h2>
      <ul>
        <li>本地文件采用分片上传，中断后可续传；按文件内容去重，重复上传同一文件会复用已有的转写与摘要。</li>
        <li>支持粘贴视频链接导入（如常见的视频站点），由服务端下载入库；链接导入失败的任务需要删除后重新创建。</li>
        <li>上传完成只表示视频已入库，<strong>转写、摘要等处理需要在视频详情页手动启动</strong>，上传结果会提示下一步操作。</li>
      </ul>

      <h2 id="transcription">语音转写</h2>
      <p>
        转写是摘要、索引和问答的前提。长音频按时间窗切成多个分片并行处理，详情页实时显示分片进度、当前分片的时间范围、重试与限流等待原因，以及已完成分片的文字。页面同时显示服务端允许的并发上限，便于判断任务是在排队还是已经在调用。
      </p>

      <h2 id="visual">画面证据（可选）</h2>
      <p>
        转写时可同时进行抽帧、画面文字识别（OCR）和画面描述，生成带时间的画面证据。每个视频的详情页提供「后续生成画面证据」开关：对于主要依靠语音内容的视频可以关闭，关闭后转写、摘要照常进行，但不新增画面证据；已有的画面证据和索引保留。抽帧预算覆盖全片片头到片尾，详情页会显示证据的实际覆盖范围，并在未覆盖后段时明确提示。
      </p>

      <h2 id="summary">视频摘要</h2>
      <p>
        转写完成后可生成全片摘要。长转写会先分段生成要点、再合并成完整报告，页面显示分段与合并进度；某一段失败时任务按失败处理，可以从失败处继续，不会把不完整的合并结果显示为成功摘要。摘要失败会按网络、超时、上游服务错误、限流等类别提示，并附可复制的诊断编号，便于对照后台日志排查。
      </p>

      <h2 id="index">检索索引</h2>
      <p>
        索引把已有转写（及已生成的画面文字）切分后发给配置的向量模型，生成用于语义检索的向量。只播放视频、看转写或摘要时不需要索引；要使用语义检索和视频问答则需要先建立。索引有「待建 / 排队 / 构建中 / 已建立 / 失败 / 需要重建」等状态，构建中会显示已处理的文本块数与等待原因，重复触发会被服务端拒绝。转写或画面证据更新后，索引会提示「需要重建」，重建会替换旧向量并再次消耗 Embedding 额度。
      </p>

      <h2 id="qa">问答</h2>
      <p>侧栏「问答」提供独立入口，支持三种范围，范围会一直显示在页面顶部：</p>
      <ul>
        <li><strong>单视频</strong>：只使用所选视频的证据，适合追问细节；页面带迷你播放器，引用可直接回放。</li>
        <li><strong>视频库</strong>：跨当前账号已建索引的全部视频检索（仅 Chat 模式）。</li>
        <li><strong>知识库</strong>：只检索知识库成员视频，适合按主题研究。</li>
      </ul>
      <p>两种对话方式：</p>
      <ul>
        <li><strong>Chat</strong>：直接检索相关片段并流式生成回答，适合自然问答、解释与总结。</li>
        <li><strong>Agent</strong>：在预算内自主调用检索、查看画面等工具，逐步分析；执行计划、工具调用和证据覆盖在侧栏实时可见。视频库范围暂不提供 Agent。</li>
      </ul>
      <p>
        已有转写和摘要的视频会给出几条推荐问题，点击即可发问。回答中的引用保留视频来源与时间，可查看上下文并跳转回放；回答末尾显示本轮状态与耗时。检索因限流等原因不可用时，回答会明确标记「检索降级 · 无引用」，不会把无证据的回答伪装成检索结果。执行过程的步骤摘要会随回答保存，离开后再回到会话仍可复盘。
      </p>

      <h2 id="kb">知识库</h2>
      <p>
        知识库是用户自建的视频分组（名称 + 描述 + 成员视频），作为独立的检索与问答边界。只有已建索引的视频才能加入知识库。知识库详情页可以管理成员、进入知识库问答，或使用检索测试台直接调试检索命中。
      </p>

      <h2 id="memory">长期记忆</h2>
      <p>
        在你明确授权后，系统可以从对话中抽取需要长期沿用的偏好（如回答语言、详略、格式），在后续会话中参考。「设置 → 记忆」中可以查看全部记忆、逐条撤回或彻底删除；个人总开关默认关闭，关闭后不读取也不新增记忆，但不会删除已有记忆。
      </p>

      <h2 id="prompt">提示词偏好</h2>
      <p>
        「设置 → 提示词」按功能展示问答、摘要、画面描述、Agent 回答等实际使用的固定指令和适用范围，并允许为每个功能保存自己的偏好（例如回答风格、语言要求）。偏好只影响之后的新请求，不会改写已完成的摘要、画面证据或会话记录；可以随时恢复默认。
      </p>

      <h2 id="appearance">外观与其他</h2>
      <ul>
        <li>深色 / 浅色主题，在侧栏或设置页切换，选择会被记住。</li>
        <li>问答会话提供按问题的导航目录，长会话中可快速跳转；窄屏下目录可折叠。</li>
        <li>AI 配置支持导出为 JSON（不含密钥）并在其他环境导入，密钥需要重新填写。</li>
      </ul>
    </article>
  )
}
