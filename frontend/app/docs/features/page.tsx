

export default function DocsFeaturesPage() {
  return (
    <article className="docs-article">
      <h1>功能说明</h1>
      <p className="docs-lede">从导入视频、回看证据到整理笔记与持续修订，按使用顺序了解映知的主要能力。</p>

      <h2 id="workspace">工作台与视频库</h2>
      <p>
        工作台（首页）提供「继续学习」入口，并汇总处理中的视频、后台生成的学习笔记、最近成果和问答会话；有运行中的任务时会更新状态。视频库展示当前账号的视频，支持按状态筛选和关键词搜索。视频卡片下方的四段进度条依次表示「入库 / 转写 / 画面分析 / 检索索引」，悬停可查看各段状态；画面未执行或索引尚未建立会分别显示。
      </p>

      <h2 id="upload">上传与链接导入</h2>
      <ul>
        <li>本地文件采用分片上传。中断后重新选择同一文件，服务端仍保留的分片可以续传；上传和合并完成前请保持页面打开。</li>
        <li>相同文件可复用已经完成的转写与摘要，是否复用以返回的任务状态为准；重复上传并不保证跳过文件传输。</li>
        <li>支持粘贴视频链接，由服务端下载入库；能否下载取决于站点支持与链接访问条件。服务器受理后可以离页，链接下载失败需删除任务后重新导入。</li>
        <li>新视频入库后，<strong>需要在详情页点击「先完成转写」才会启动处理</strong>。视频已有处理结果时，页面会提供相应的阅读、重新生成或重建入口。</li>
      </ul>

      <h2 id="transcription">语音转写</h2>
      <p>
        转写是摘要、索引和问答的前提。长音频按时间窗切成多个分片并行处理，详情页实时显示分片进度、当前分片的时间范围、重试与限流等待原因，以及已完成分片的文字。页面同时显示服务端允许的并发上限，便于判断任务是在排队还是已经在调用。
      </p>

      <h2 id="visual">画面证据（可选）</h2>
      <p>
        配置了可用的视觉能力后，转写流程可同时抽帧、识别画面文字（OCR）并生成画面描述。详情页显示帧处理进度、失败或跳过原因，以及已保存画面的实际覆盖范围。抽帧是对视频的采样，不能据此认为每个画面都已分析。
      </p>
      <p>
        「后续生成画面证据」开关控制这个视频后续的视觉处理。关闭后，转写和摘要照常进行，也不再通过问答按需抽帧；已有画面证据和索引保留。重新开启不会立即补做，需要再次转写才会重新生成；新视觉记录生成后，页面会提示重建索引。
      </p>

      <h2 id="summary">视频摘要</h2>
      <p>
        转写完成后可生成全片摘要。系统按模型配置的上下文容量决定整篇生成或先分段生成要点、再合并报告；分段处理时，页面显示分段、合并进度与失败位置，未完成的合并结果不会作为成功摘要发布。失败时页面按网络、超时、上游服务错误、限流等类别给出提示，并说明是否等待自动重试；需要手动处理时可按页面提示重试，已有可复用的分段结果会保留。可复制诊断编号协助排查。
      </p>

      <h3 id="summary-revision">修改摘要与记住术语</h3>
      <p>
        打开视频摘要后，可以描述修改要求，先预览逐处差异，再确认保存。修订只属于当前账号；可以撤销这次摘要修改，也可以下载当前显示的摘要 Markdown。生成原稿后来更新时，页面会提示选择「保留我的修订」或「改用新原稿」。
      </p>
      <p>
        名称纠正可以选择「只改这次」，或填写原写法、使用名称、适用上下文与排除条件，保存为此视频的术语规则。规则只影响后续新运行，不会重写原始转写或画面记录；没有证据支持的规则会标为用户指定。规则可单独停用，撤销摘要不会自动撤销规则。也可以同时选择一份已有学习笔记发起修订，摘要、笔记与规则分别保存、分别报告结果，失败的目标可单独重试。
      </p>

      <h2 id="study-notes">学习笔记与成果库</h2>
      <p>
        在视频详情页或侧栏「成果」中，选择一个已完成转写且不在处理中的视频，填写学习目标，即可生成包含章节、概念与示例的学习笔记。当前支持单视频学习笔记，不要求先建立检索索引。任务使用提交时的默认模型与执行预算，在后台完成分段整理、结构组织和引用校验；成果库保留生成后的笔记，供后续阅读和修改。
      </p>
      <ul>
        <li><strong>依据与回看</strong>：每个段落可关联多条转写或画面证据，在证据栏逐条查看并回放。粗粒度时间会提示结合上下文核对；时间未知时不提供定位回放，来源更新后也不会用旧快照的时间定位新内容。</li>
        <li><strong>人工编辑</strong>：可以改标题和正文、新增章节或子块、移动层级、合并同级内容与删除子树。编辑完成后点击「保存修改」；人工修改后的引用仍需核对。</li>
        <li><strong>版本记录</strong>：保存会创建新版本，历史版本可只读查看。保存遇到其他页面的新修改时，会保留本地草稿并提供版本比较；可以先下载草稿，再决定是否加载服务器版本。</li>
        <li><strong>重新整理</strong>：可从视频页重新生成同一份笔记。生成期间若笔记已被修改，新结果会作为候选保留，查看后再选择采用。</li>
        <li><strong>Markdown 导出</strong>：点击「导出 Markdown」准备文件，再点击下载；导出包含已保存正文与来源引用，有未保存修改时需先保存。</li>
      </ul>
      <p>生成内容是待核对的学习材料。名称、命令、层级与引用关系仍需结合原视频确认，引用存在并不代表结论已经核实。</p>

      <h3 id="artifact-edit">让 Agent 修订笔记</h3>
      <p>
        在笔记顶部可以让 Agent 修改全文，也可以从具体段落或导图节点发起局部修订。局部范围包含选中块及其子段落；有未保存的人工修改时，需要先保存再提交要求。
      </p>
      <ul>
        <li><strong>只核对，不修改</strong>：读取当前笔记和必要依据，返回核对结果。</li>
        <li><strong>先看修改方案</strong>：查看修改前后内容、层级、位置和引用差异，确认后应用。</li>
        <li><strong>直接保存修改</strong>：按要求执行并创建新版本，之后仍可查看差异；符合撤销条件时可用「撤销这次修改」创建撤销版本。</li>
      </ul>
      <p>
        修订运行在后台继续，关闭面板不会取消；回到成果页可以继续查看或取消运行。若当前版本已变化或后续编辑与撤销发生冲突，页面会提示重新核对，不会直接覆盖新版本。
      </p>

      <h3 id="canvas">思维导图与知识画布</h3>
      <p>
        「学习笔记」「思维导图」「知识画布」共用同一份内容。思维导图用于浏览章节与概念层级，选择节点可以查看正文和关联依据；切换到知识画布后，可以拖动、固定、折叠或隐藏卡片，使用横向、纵向或选中分支排版，并撤销、重做布局。
      </p>
      <p>
        画布位置、折叠和隐藏状态会单独保存；隐藏节点不会删除正文。节点改名以及添加或移除「相关 / 依赖 / 对比」关系会进入笔记草稿，需要点击「保存修改」。连线不改变章节层级。AI 排版按要求调整布局；让 Agent 修改图内容则进入笔记修订流程。普通思维导图由笔记直接生成，不额外调用模型，AI 排版与内容修订会调用模型。
      </p>

      <h2 id="tasks">任务中心</h2>
      <p>
        侧栏「任务」汇总视频处理和学习笔记生成。视频任务可查看转写、画面与索引状态并进入详情页；笔记生成任务显示排队、来源整理、生成、结构整理、校验和保存阶段，以及模型调用与 Token 用量。Token 会区分实际、估算或尚未确认。
      </p>
      <p>
        生成请求受理后可以离开页面。根据任务当前状态，详情面板提供取消、请求恢复或重新生成入口；取消请求需要后台确认，失败或预算不足时可先检查原因和配置再重试。笔记 Agent 修订回到成果页查看，摘要修订回到视频摘要查看。
      </p>

      <h2 id="study-resume">继续学习、段落提问与回答收录</h2>
      <p>
        播放视频或选择已保存笔记的段落后，系统会同步当前账号的学习位置。首页「继续学习」可回到最近记录的视频时间或笔记段落；原版本、段落发生变化时会回退到可阅读的位置并提示。同步失败时以页面提示为准。
      </p>
      <p>
        笔记中的「围绕这段提问」会把已保存段落带入该视频的问答，并提供返回原段落的入口。同一视频中已完整保存的回答可收进已有笔记：先选择插入位置、预览正文和引用，再确认保存新版本。聊天引用无法对应目标笔记来源时，可以取消，或明确选择把整段作为无来源个人补充；收录后的内容标为人工整理、待核对。
      </p>

      <h2 id="index">检索索引</h2>
      <p>
        索引把已有转写、画面文字和画面描述（如有）切分后发给配置的向量模型，生成用于语义检索的向量。只播放视频、看转写、摘要或生成学习笔记时不需要索引；使用语义检索和基于检索的视频问答前，需要先建立。索引有「待建 / 排队 / 构建中 / 已建立 / 失败 / 需要重建」等状态，构建中会显示已处理的文本块数与等待原因；转写或画面证据更新后会提示重建。重建会替换旧向量并再次消耗 Embedding 额度。
      </p>

      <h2 id="qa">问答</h2>
      <p>侧栏「问答」提供独立入口，支持三种范围，范围会一直显示在页面顶部：</p>
      <ul>
        <li><strong>单视频</strong>：只使用所选视频的证据，适合追问细节；页面带迷你播放器，引用可直接回放。</li>
        <li><strong>视频库</strong>：跨当前账号已用当前向量模型建立索引的视频检索（仅 Chat 模式）。</li>
        <li><strong>知识库</strong>：只检索知识库成员视频，适合按主题研究。</li>
      </ul>
      <p>两种对话方式：</p>
      <ul>
        <li><strong>Chat</strong>：直接检索相关片段并流式生成回答，适合自然问答、解释与总结。</li>
        <li><strong>Agent</strong>：在预算内自主调用检索、查看画面等工具，逐步分析；工具调用、命中证据和运行状态在侧栏实时可见。知识库内的 Agent 入口名为「跨视频研究」，视频库范围暂不提供 Agent。</li>
      </ul>
      <p>
        单视频问答提供基于已有内容的推荐问题，点击即可发问。回答中的引用可查看来源上下文，有可靠时间时可以跳转回放；回答末尾显示本轮状态与耗时。检索因限流等原因不可用时，页面会标记「检索降级 · 无引用」。已保存回答的执行步骤可以在回到会话后复盘；聊天期间若离页或中断，需回到会话核对本轮是否完整保存。
      </p>

      <h2 id="kb">知识库</h2>
      <p>
        知识库是用户自建的视频分组（名称 + 描述 + 成员视频），作为独立的检索与问答边界。只有已用当前默认向量模型建立索引的视频才能加入知识库。知识库详情页可以管理成员、进入知识库问答，或使用检索测试台直接调试检索命中。
      </p>

      <h2 id="memory">长期记忆</h2>
      <p>
        服务端启用记忆能力后，在「设置 → 记忆治理」开启长期记忆，并在对话中明确表达需要长期沿用的偏好，系统可保存回答语言、详略和格式，供后续 Chat 与 Agent 会话参考。个人开关默认关闭；关闭后不读取也不新增记忆，已有记录保留。设置页可以查看用户范围的记忆、逐条撤回或彻底删除；Agent 也可读取已授权视频或知识库范围内的既有记忆，视频事实仍需按当轮证据核对。
      </p>

      <h2 id="prompt">提示词偏好</h2>
      <p>
        「设置 → 提示词」展示固定指令和适用范围，可分别保存普通问答、摘要、画面描述与 Agent 最终回答的个人偏好（例如回答风格、语言要求）；规划器、自动标题等固定规则只供查看。偏好只影响对应功能之后的新请求，不会改写已完成的摘要、画面证据或会话记录；留空并保存即可恢复默认。
      </p>

      <h2 id="appearance">外观与其他</h2>
      <ul>
        <li>深色 / 浅色主题，在侧栏或设置页切换，选择会被记住。</li>
        <li>问答会话提供按问题的导航目录，长会话中可快速跳转；窄屏下目录可折叠。</li>
        <li>AI 配置支持导出为 JSON（不含密钥）并在其他环境导入，密钥需要重新填写。</li>
      </ul>
    </article>
  )
}
